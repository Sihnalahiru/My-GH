/* BUILD-11 — Study Mode Validator */
(function () {
  "use strict";

  async function loadJSON(path) {
    const response = await fetch(path, { cache: "no-cache" });
    if (!response.ok) throw new Error(`${path}: ${response.status}`);
    return response.json();
  }

  async function validateStudyMode() {
    const [study, sources] = await Promise.all([
      loadJSON("data/study.json"),
      loadJSON("data/sources.json")
    ]);

    if (!window.SSWStudyMode) {
      throw new Error("BUILD-11 Study Mode engine is not loaded.");
    }

    const sourceMap = new Map(
      (sources.sources || []).map(source => [
        source.source_id,
        source
      ])
    );

    const blocks = (study.study_blocks || [])
      .map(window.SSWStudyMode.normalizeStudyBlock)
      .filter(Boolean);

    const errors = [];
    const warnings = [];
    const ids = new Set();

    for (const block of blocks) {
      if (ids.has(block.study_id)) {
        errors.push(`STUDY-009: duplicate study_id ${block.study_id}`);
      }
      ids.add(block.study_id);

      const result = window.SSWStudyMode.validateStudyBlock(
        block,
        { sources: sourceMap }
      );

      if (!result.valid) {
        errors.push({
          study_id: block.study_id,
          errors: result.errors
        });
      }

      warnings.push(
        ...result.warnings.map(warning => ({
          study_id: block.study_id,
          warning
        }))
      );
    }

    return {
      build_step: "BUILD-11",
      status: errors.length ? "FAIL" : "PASS",
      counts: {
        total: blocks.length,
        verified: blocks.filter(
          b => b.status === "VERIFIED" &&
               b.verification_status === "VERIFIED"
        ).length,
        pending: blocks.filter(
          b => b.status === "PENDING"
        ).length
      },
      errors,
      warnings,
      rules: [
        "Study Mode consumes verified study blocks.",
        "Source provenance is mandatory.",
        "Substantive verified content requires Sinhala explanation.",
        "Pending terminology and visuals are not silently promoted.",
        "Study Mode may expose richer explanations than Real Exam Mode.",
        "Language-name labels are not generated by the engine."
      ]
    };
  }

  window.validateSSWStudyMode = validateStudyMode;
})();

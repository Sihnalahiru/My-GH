const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const progress=require(path.join(root,'app','progress.js'));
const errors=[];
if(progress.STORAGE_KEY!=='ssw-gh-progress-v1') errors.push('Unexpected canonical storage key');
if(!progress.EVENT_TYPES.STUDY_OPEN||!progress.EVENT_TYPES.MCQ_ANSWER||!progress.EVENT_TYPES.EXAM_COMPLETE||!progress.EVENT_TYPES.AUDIO_PLAY) errors.push('Required event types missing');
const storage=new Map();
const fake={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
storage.set('ssw-gh-progress',JSON.stringify({seen:['GH01-F001'],history:[{question_id:'GH01-SBP-Q001',correct:true,at:Date.now()}]}));
storage.set('ssw-aviation-study-progress-v1',JSON.stringify({opened:{'GH01-F002':Date.now()},completed:{'GH01-F002':{completed_at:new Date().toISOString()}}}));
const store=new progress.ProgressStore({storage:fake});
const a=progress.buildAnalytics(store);
if(!a.totals.mcq_answered||a.totals.mcq_correct!==1) errors.push('Legacy MCQ migration failed');
if(a.totals.study_opened<2) errors.push('Legacy study migration failed');
store.recordAudioPlay({track:'GROUND_HANDLING',fact_id:'GH01-F001',source:'AUDIO'});
if(progress.buildAnalytics(store).totals.audio_plays!==1) errors.push('Audio progress event failed');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
if(/localStorage\.getItem\("ssw-gh-progress"\)/.test(app)||/state\.progress\b/.test(app)) errors.push('app.js still owns legacy progress state');
const study=fs.readFileSync(path.join(root,'app','study.js'),'utf8');
if(/ssw-aviation-study-progress-v1/.test(study)) errors.push('study.js still owns legacy storage');
console.log(JSON.stringify({valid:errors.length===0,errors,canonical_storage_key:progress.STORAGE_KEY,migrated_totals:a.totals},null,2));
process.exit(errors.length?1:0);
